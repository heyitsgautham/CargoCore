"""
ai.py
Pydantic v2 request/response schemas for the AI chatbot endpoints.
"""
from datetime import datetime
from uuid import UUID

from pydantic import BaseModel, Field

# ── Request Schemas ───────────────────────────────────────────────────────────

class ChatRequest(BaseModel):
    message: str = Field(
        ...,
        min_length=1,
        max_length=2000,
        description="The user's message to the AI chatbot.",
    )
    context: str | None = Field(
        default=None,
        description="Optional module context such as warehouse_management or vendor_dashboard.",
    )
    session_id: UUID | None = Field(
        default=None,
        description="Existing conversation session ID. Omit to start a new conversation.",
    )
    order_id: UUID | None = Field(
        default=None,
        description="Linked order/shipment for support-chat flows.",
    )


class AgentReplyRequest(BaseModel):
    message: str = Field(
        ...,
        min_length=1,
        max_length=2000,
        description="Human agent reply to append to an AI conversation session.",
    )


class ContactSubmissionCreatePublic(BaseModel):
    name: str = Field(..., min_length=2, max_length=255)
    email: str = Field(..., min_length=3, max_length=255)
    phone: str | None = Field(default=None, max_length=40)
    subject: str = Field(..., min_length=2, max_length=255)
    category: str = Field(default="general", min_length=2, max_length=50)
    priority: str = Field(default="medium", min_length=2, max_length=20)
    message: str = Field(..., min_length=5, max_length=5000)


class ContactSubmissionUpdate(BaseModel):
    status: str | None = Field(default=None, max_length=20)
    priority: str | None = Field(default=None, max_length=20)
    assigned_to_user_id: UUID | None = None
    notes: str | None = Field(default=None, max_length=5000)


class ContactSubmissionReplyRequest(BaseModel):
    message: str = Field(..., min_length=1, max_length=5000)


class SupportSessionEscalateRequest(BaseModel):
    reason: str = Field(..., min_length=1, max_length=1000)


# ── Response Schemas ──────────────────────────────────────────────────────────

class ChatResponse(BaseModel):
    session_id: UUID
    message: str
    intent: str | None = Field(
        default=None,
        description="Classified intent: db_query, general, greeting, error",
    )
    sql_generated: str | None = Field(
        default=None,
        description="The SQL query generated by the AI (if any). Useful for transparency.",
    )
    requires_human: bool = Field(
        default=False,
        description="Whether this response triggered or requires human support follow-up.",
    )
    human_handoff_reason: str | None = Field(
        default=None,
        description="Reason shown when the conversation was handed to human support.",
    )
    human_handoff_locked: bool = Field(
        default=False,
        description="Whether the current session can no longer be escalated to a human agent.",
    )
    linked_order_id: UUID | None = Field(
        default=None,
        description="Linked order/shipment for the current support-chat session.",
    )
    linked_order_tracking_code: str | None = Field(
        default=None,
        description="Tracking code for the linked order/shipment.",
    )


class ConversationMessage(BaseModel):
    role: str = Field(description="'user' or 'assistant'")
    message: str
    intent: str | None = None
    sql_generated: str | None = None
    created_at: datetime

    model_config = {"from_attributes": True}


class ConversationHistory(BaseModel):
    session_id: UUID
    messages: list[ConversationMessage]


class SessionListItem(BaseModel):
    session_id: UUID
    last_message: str
    message_count: int
    created_at: datetime


class SessionListResponse(BaseModel):
    sessions: list[SessionListItem]


class SupportAgentSummary(BaseModel):
    id: UUID
    name: str
    email: str | None = None

    model_config = {"from_attributes": True}


class ContactSubmissionResponse(BaseModel):
    id: UUID
    reference_code: str
    name: str
    email: str
    phone: str | None = None
    subject: str
    category: str
    message: str
    priority: str
    status: str
    notes: str | None = None
    assigned_to_user_id: UUID | None = None
    assigned_agent_name: str | None = None
    created_at: datetime
    updated_at: datetime

    model_config = {"from_attributes": True}


class ContactSubmissionStats(BaseModel):
    total: int
    new: int
    in_progress: int
    resolved: int
    urgent: int


class ContactSubmissionListResponse(BaseModel):
    submissions: list[ContactSubmissionResponse]
    stats: ContactSubmissionStats
    agents: list[SupportAgentSummary]


class SupportSessionEscalationSummary(BaseModel):
    id: UUID
    status: str
    reason: str
    escalated_at: datetime
    resolved_at: datetime | None = None
    escalated_to_user_id: UUID | None = None
    assigned_agent_name: str | None = None


class SupportSessionListItem(BaseModel):
    session_id: UUID
    user_id: UUID
    user_name: str
    user_email: str | None = None
    user_role: str | None = None
    user_phone: str | None = None
    first_message_at: datetime
    last_message: str
    last_message_role: str
    last_message_at: datetime
    message_count: int
    latest_order_tracking_code: str | None = None
    sentiment: str | None = None
    human_agent_engaged: bool = False
    assigned_agent_name: str | None = None
    needs_human_attention: bool = False
    attention_reason: str | None = None
    escalation: SupportSessionEscalationSummary | None = None


class SupportSessionListResponse(BaseModel):
    sessions: list[SupportSessionListItem]


class SupportConversationMessage(BaseModel):
    id: UUID
    role: str
    message: str
    intent: str | None = None
    created_at: datetime
    author_name: str | None = None
    author_role: str | None = None

    model_config = {"from_attributes": True}


class SupportSessionDetail(BaseModel):
    session: SupportSessionListItem
    messages: list[SupportConversationMessage]


class SupportDashboardStats(BaseModel):
    total_sessions: int
    active_sessions: int
    human_engaged_sessions: int
    sessions_needing_human: int
    open_escalations: int
    open_contact_forms: int
    new_contact_forms: int
    resolved_contact_forms: int
    user_messages_today: int
    assistant_messages_today: int


class SupportDashboardFeedItem(BaseModel):
    id: str
    type: str
    title: str
    description: str
    created_at: datetime


class SupportDashboardResponse(BaseModel):
    stats: SupportDashboardStats
    priority_sessions: list[SupportSessionListItem]
    recent_contact_submissions: list[ContactSubmissionResponse]
    activity_feed: list[SupportDashboardFeedItem]


class SupportAnalyticsMetric(BaseModel):
    id: str
    label: str
    icon: str
    value: float
    formatted_value: str
    trend: str
    trend_direction: str


class SupportAnalyticsResolutionChart(BaseModel):
    labels: list[str]
    ai_resolved: list[int]
    human_escalated: list[int]


class SupportAnalyticsEscalationReason(BaseModel):
    label: str
    count: int
    pct: int


class SupportAnalyticsSentimentChart(BaseModel):
    labels: list[str]
    ai_handled: list[float]
    human_handled: list[float]


class SupportAnalyticsInsight(BaseModel):
    id: str
    icon: str
    title: str
    text: str
    tone: str = Field(description="purple, blue, amber, red, or green")
    action_label: str = "Take Action"
    executed: bool = False


class SupportAnalyticsResponse(BaseModel):
    range: str
    generated_at: datetime
    metrics: list[SupportAnalyticsMetric]
    resolution_chart: SupportAnalyticsResolutionChart
    escalation_reasons: list[SupportAnalyticsEscalationReason]
    sentiment_chart: SupportAnalyticsSentimentChart
    insights: list[SupportAnalyticsInsight]


class SupportAnalyticsInsightExecutionResponse(BaseModel):
    insight_id: str
    ticket_id: UUID
    ticket_reference_code: str
    message: str


class SupportIntegrationStatus(BaseModel):
    provider: str
    label: str
    description: str
    connected: bool
    connection_source: str
    status_note: str
    editable: bool = False


class SupportSettings(BaseModel):
    tone: str = Field(..., min_length=2, max_length=60)
    language_mode: str = Field(..., min_length=2, max_length=60)
    sentiment_threshold: int = Field(..., ge=0, le=100)
    refund_limit_inr: int = Field(..., ge=0, le=500000)
    system_prompt: str = Field(..., min_length=20, max_length=20000)
    autonomous_replies: bool = True
    legal_threat_detection: bool = True
    real_time_sentiment_analysis: bool = True
    proactive_human_handover: bool = False


class SupportSettingsResponse(BaseModel):
    settings: SupportSettings
    integrations: list[SupportIntegrationStatus]
    updated_at: datetime | None = None
    autonomous_reply_guidance: str
    rag_recommended: bool


